#!/usr/bin/env node
/**
 * The Phase 9 UI gate (docs/UI-SPEC.md "Verification at every UI gate").
 *
 * Scope note: docs/UI-SPEC.md's own reference command
 * (`skills/webapp-testing/scripts/with_server.py --server "cd web && npm
 * run dev" ... python eval/ui/gate.py`) names a Python/Playwright toolchain
 * that doesn't exist as an installed skill script in this environment
 * (the same situation as `skills/ui-ux-pro-max/scripts/search.py`,
 * documented in phases/reports/PHASE-09.md). This is the honest
 * substitute: Node + Playwright, doing the same checks against a real
 * Chromium instance, run from `web/` with `node ../eval/ui/gate.mjs`
 * while `npm run dev` (or `next start`) is already serving on :3000.
 *
 * Checks, per docs/UI-SPEC.md:
 *   - axe-core: zero critical/serious violations, every surface, both themes
 *   - no forbidden watermark strings in the rendered DOM
 *   - keyboard traversal reaches the first N focusable elements with a
 *     visible :focus-visible ring
 *   - screenshots at 1280 / 1920 / 2560 x both themes, written to
 *     phases/reports/screenshots/
 *
 * Does NOT check (out of Phase 9's scope, noted honestly):
 *   - the 10k-node graph canvas fps floor (Investigation Canvas doesn't
 *     exist until Phase 11)
 *   - CLS/LCP on a throttled profile (needs real data-bearing surfaces)
 */
import { chromium } from "playwright";
import { readFileSync } from "node:fs";
import { mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");
const SCREENSHOT_DIR = path.join(REPO_ROOT, "phases", "reports", "screenshots");
const AXE_SOURCE = readFileSync(
  path.join(REPO_ROOT, "web", "node_modules", "axe-core", "axe.min.js"),
  "utf-8",
);
const BASE_URL = process.env.GATE_BASE_URL ?? "http://localhost:3000";

const SURFACES = [
  "/", "/investigation-canvas", "/timeline", "/verdict-ledger", "/drift-monitor",
  "/response-console", "/coverage-map", "/detection-studio", "/tenant-admin",
];

const WATERMARK_PATTERNS = [
  /generated by/i, /built with/i, /powered by/i, /made with ai/i,
  /claude/i, /anthropic/i, /chatgpt/i, /openai/i,
];

const WIDTHS = [1280, 1920, 2560];

async function signIn(page) {
  await page.goto(`${BASE_URL}/login`);
  await page.fill("#email", "gate-runner@tenant.example");
  await page.selectOption("#role", "admin");
  await Promise.all([page.waitForURL(`${BASE_URL}/`), page.click('button[type="submit"]')]);
}

async function checkWatermarks(page, label, failures) {
  const html = await page.content();
  for (const pattern of WATERMARK_PATTERNS) {
    if (pattern.test(html)) {
      failures.push(`watermark: ${label} matched forbidden pattern ${pattern}`);
    }
  }
}

async function checkAxe(page, label, theme, failures) {
  await page.addScriptTag({ content: AXE_SOURCE });
  const results = await page.evaluate(() =>
    window.axe.run(document, { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa"] } }),
  );
  const serious = results.violations.filter((v) => v.impact === "critical" || v.impact === "serious");
  if (serious.length > 0) {
    failures.push(
      `axe: ${label} (${theme}) has ${serious.length} critical/serious violation(s): ` +
        serious.map((v) => `${v.id} (${v.nodes.length} nodes)`).join(", "),
    );
  }
  return results.violations.length;
}

async function checkKeyboardTraversal(page, failures) {
  await page.goto(`${BASE_URL}/`);
  await page.evaluate(() => document.body.focus());
  let visibleCount = 0;
  for (let i = 0; i < 8; i++) {
    await page.keyboard.press("Tab");
    const matches = await page.evaluate(() => {
      const el = document.activeElement;
      return el ? el.matches(":focus-visible") : false;
    });
    if (matches) visibleCount++;
  }
  if (visibleCount < 6) {
    failures.push(`keyboard: only ${visibleCount}/8 tab stops showed a visible focus ring`);
  }
}

async function main() {
  mkdirSync(SCREENSHOT_DIR, { recursive: true });
  const browser = await chromium.launch();
  const failures = [];
  let totalViolations = 0;

  for (const theme of ["dark", "light"]) {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    const page = await context.newPage();
    await signIn(page);
    await page.evaluate((t) => localStorage.setItem("theme", t), theme);
    await page.reload();
    await page.waitForTimeout(300);

    for (const surface of SURFACES) {
      await page.goto(`${BASE_URL}${surface}`);
      await page.waitForTimeout(200);
      await checkWatermarks(page, surface, failures);
      totalViolations += await checkAxe(page, surface, theme, failures);
    }

    if (theme === "dark") {
      await checkKeyboardTraversal(page, failures);
    }

    // Screenshots: Watchfloor at three widths, this theme.
    for (const width of WIDTHS) {
      await page.setViewportSize({ width, height: Math.round(width * 0.625) });
      await page.goto(`${BASE_URL}/`);
      await page.waitForTimeout(200);
      const file = path.join(SCREENSHOT_DIR, `watchfloor-${theme}-${width}.png`);
      await page.screenshot({ path: file });
      console.log(`wrote ${file}`);
    }

    await context.close();
  }

  await browser.close();

  console.log(`\naxe-core: ${totalViolations} total violation(s) across all surfaces/themes (any impact level)`);

  if (failures.length > 0) {
    console.error("\nGATE FAILED:");
    for (const f of failures) console.error(`  - ${f}`);
    process.exit(1);
  }

  console.log("\nGATE PASSED");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
